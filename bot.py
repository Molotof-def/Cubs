async def launch_new_quiz(chat_id: int, forced_by_admin: bool = False):
    """Генерация и публикация вопроса с 4 кнопками вариантов."""
    # Если в чате уже висит активная викторина — удаляем старую
    active_quizzes.pop(chat_id, None)

    reward = random.randint(60000, 150000)
    item = random.choice(QUIZ_DATABASE)
    
    # Собираем все 4 варианта и перемешиваем
    all_options = [item["correct"]] + item["wrong"]
    random.shuffle(all_options)
    correct_idx = all_options.index(item["correct"])
    
    quiz_id = uuid.uuid4().hex[:8]
    
    active_quizzes[chat_id] = {
        "quiz_id": quiz_id,
        "question": item["q"],
        "options": all_options,
        "correct_idx": correct_idx,
        "correct_text": item["correct"],
        "reward": reward,
        "blocked_users": set(),  # Множество игроков, ответивших неверно
        "created_at": time.time()
    }

    prefix = "⚡️ <b>ВНЕОЧЕРЕДНАЯ ВИКТОРИНА АДМИНИСТРАТОРА!</b>" if forced_by_admin else "⚡️ <b>ИНТЕЛЛЕКТУАЛЬНАЯ ВИКТОРИНА!</b>"
    
    text = (
        f"{prefix}\n"
        f"━━━━━━━━━━━━━━━━━━━━\n"
        f"❓ <b>Вопрос:</b> {item['q']}\n\n"
        f"💰 Награда победителю: <b>+{fmt_num(reward)} 💰</b> на баланс!\n"
        f"⚠️ <i>Внимание: даётся только ОДНА попытка. При ошибке вы выбываете из этого раунда!</i>\n"
        f"━━━━━━━━━━━━━━━━━━━━\n"
        f"<i>Выберите один из вариантов ниже:</i>"
    )

    try:
        await bot.send_message(
            chat_id=chat_id,
            text=text,
            parse_mode="HTML",
            reply_markup=quiz_options_keyboard(quiz_id, all_options)
        )
    except Exception as e:
        logger.error(f"Не удалось отправить викторину в чат {chat_id}: {e}")
        active_quizzes.pop(chat_id, None)

@dp.callback_query(F.data.startswith("qans_"))
async def cb_handle_quiz_click(call: CallbackQuery):
    """Обработка клика по кнопке с вариантом ответа."""
    parts = call.data.split("_")
    if len(parts) < 3:
        return await call.answer()

    quiz_id = parts[1]
    try:
        chosen_idx = int(parts[2])
    except ValueError:
        return await call.answer()

    chat_id = call.message.chat.id
    user_id = call.from_user.id
    user_name = call.from_user.full_name

    quiz = active_quizzes.get(chat_id)
    if not quiz or quiz["quiz_id"] != quiz_id:
        return await call.answer("❌ Этот раунд викторины уже завершён или устарел!", show_alert=True)

    # Проверка: если игрок уже ошибся в этом раунде
    if user_id in quiz["blocked_users"]:
        return await call.answer("🚫 Вы уже дали неправильный ответ и выбыли из этой викторины!", show_alert=True)

    # Если ответ ПРАВИЛЬНЫЙ
    if chosen_idx == quiz["correct_idx"]:
        reward = quiz["reward"]
        correct_text = quiz["correct_text"]
        active_quizzes.pop(chat_id, None)

        await db.register_user(user_id, user_name, call.from_user.username)
        await db.change_balance(user_id, reward)
        
        u_data = await db.get_user(user_id)
        display_name = (u_data.get("custom_nick") or user_name) if u_data else user_name

        try:
            await call.message.edit_reply_markup(reply_markup=None)
        except Exception:
            pass

        win_text = (
            f"🎉 <b>ПОБЕДА В ВИКТОРИНЕ!</b>\n\n"
            f"👤 Победитель: {get_mention(user_id, display_name)}\n"
            f"✅ Верный ответ: <b>{correct_text}</b>\n"
            f"💰 Приз за эрудицию: <b>+{fmt_num(reward)} монет</b> зачислен на баланс!"
        )
        await call.message.answer(win_text, parse_mode="HTML")
        await call.answer("🏆 Абсолютно верно! Приз ваш!", show_alert=True)
    else:
        # Если ответ НЕПРАВИЛЬНЫЙ — баним участника в этом вопросе
        quiz["blocked_users"].add(user_id)
        await call.answer("❌ Ответ неверный! Вы выбыли из этой викторины.", show_alert=True)

async def quiz_background_worker():
    """Фоновый таймер викторины: запускается строго раз в 30 минут."""
    await asyncio.sleep(30)
    while True:
        try:
            await asyncio.sleep(1800)  # 30 минут
            if not known_groups:
                continue

            target_chat_id = random.choice(list(known_groups))
            try:
                member_count = await bot.get_chat_member_count(target_chat_id)
                if member_count < 3:
                    continue
            except Exception:
                known_groups.discard(target_chat_id)
                continue

            await launch_new_quiz(target_chat_id, forced_by_admin=False)
        except Exception as e:
            logger.error(f"Ошибка в quiz_background_worker: {e}")
            await asyncio.sleep(30)

